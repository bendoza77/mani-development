const mediaCategory = (key: string): MediaCategory => {
  if (key.startsWith("team-")) return "team";
  if (/site|earthworks|drawings/.test(key)) return "construction";
  if (/interior|office/.test(key)) return "interior";
  return "exterior";
};

const humanise = (key: string) =>
  key.replace(/^team-/, "portrait ").replace(/-/g, " ").replace(/^\w/, (c) => c.toUpperCase());

export const seedMedia: MediaAsset[] = (Object.keys(IMAGES) as ImageKey[]).map((key, i) => {
  const meta = IMAGES[key];
  return {
    id: `a-${key}`,
    name: meta.src.split("/").pop() ?? key,
    src: meta.src,
    alt: humanise(key),
    category: mediaCategory(key),
    width: meta.width,
    height: meta.height,
    // Deterministic approximation; the originals average ~400 KB.
    size: 180_000 + ((i * 73_919) % 620_000),
    createdAt: `2026-0${(i % 9) + 1}-1${i % 9}T09:00:00Z`,
  };
});

